"""GN action "catalogue_table": catalogue.json in, a C++ table out (issue #105).

The catalogue is the fixed set of publisher addresses the browser may download a filter list from when the user
turns that list on. The addresses are compiled in: the Settings page names an id and never an address. This
tool applies the licence and address rules again at build time, so a catalogue that breaks them does not build.
tests/test_catalogue.py states the same rules independently.
"""

import argparse
import json
import re
import sys
from urllib.parse import urlsplit

ALLOWED_LICENCES = ("GPL-3.0", "GPL-3.0-or-CC-BY-SA-3.0", "CC-BY-3.0", "CC-BY-SA-3.0", "MPL-2.0")
# The order the page shows them in.
CATEGORIES = ("annoyances", "cookies", "social", "privacy", "regional")
FIELDS = {"id", "title", "description", "url", "homepage", "licence", "langs", "category", "default_enabled"}
RESERVED_IDS = ("easylist", "easyprivacy", "custom")


def _plain_https(text):
    parts = urlsplit(text) if isinstance(text, str) else None
    return bool(parts and parts.scheme == "https" and parts.hostname and "." in parts.hostname
                and not parts.username and not parts.password and not parts.fragment and len(text) <= 2048)


def validate(entries):
    """What is wrong with `entries`, as a list of sentences. Empty when it can be built."""
    if not isinstance(entries, list) or not entries:
        return ["the catalogue must be a non-empty list"]
    out, seen = [], set()
    for i, e in enumerate(entries):
        if not isinstance(e, dict) or set(e) != FIELDS:
            out.append(f"entry {i}: fields are not exactly {sorted(FIELDS)}")
            continue
        name = e["id"]
        if not isinstance(name, str) or not re.fullmatch(r"[a-z0-9]{1,32}", name):
            out.append(f"entry {i}: id must be [a-z0-9]{{1,32}}")
            continue
        if name in RESERVED_IDS or re.fullmatch(r"c[0-9a-f]{16}", name) or name in seen:
            out.append(f"{name}: id is reserved, looks like a custom list id, or is a duplicate")
        seen.add(name)
        if e["licence"] not in ALLOWED_LICENCES:
            out.append(f"{name}: licence {e['licence']!r} is not on the allow-list")
        if not _plain_https(e["url"]):
            out.append(f"{name}: url is not a plain https address")
        if not _plain_https(e["homepage"]):
            out.append(f"{name}: homepage is not a plain https address")
        if e["default_enabled"] is not False:
            out.append(f"{name}: default_enabled must be false")
        if e["category"] not in CATEGORIES:
            out.append(f"{name}: unknown category {e['category']!r}")
        if not isinstance(e["langs"], list) or not all(isinstance(x, str) and re.fullmatch(r"[a-z]{2,3}", x)
                                                        for x in e["langs"]):
            out.append(f"{name}: langs must be a list of language codes")
    return out


def _c(text):
    # A JSON string is a valid C++ string literal for the ASCII text the checks above allow.
    return json.dumps(text, ensure_ascii=True)


def render(entries):
    rows = []
    for e in entries:
        langs = ",".join(e["langs"])
        rows.append("    {%s, %s, %s, %s, %s, %s}," % (_c(e["id"]), _c(e["url"]), _c(e["homepage"]),
                                                        _c(e["licence"]), _c(e["category"]), _c(langs)))
    return """// Generated by generate_catalogue.py from catalogue.json. Do not edit.

#include "components/aerie_adblock/browser/catalogue.h"

namespace aerie_adblock {

const CatalogueEntry kCatalogueTable[] = {
%s
};
const size_t kCatalogueTableSize = std::size(kCatalogueTable);

}  // namespace aerie_adblock
""" % "\n".join(rows)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--catalogue", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    with open(args.catalogue, encoding="utf-8") as fh:
        entries = json.load(fh)
    problems = validate(entries)
    if problems:
        sys.exit("catalogue.json: " + "; ".join(problems))
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(render(entries))


if __name__ == "__main__":
    main()
