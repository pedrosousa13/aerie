class ResolveTest(unittest.TestCase):
    def test_resolve_reports_added_and_changed_entries_with_hashes(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmp = Path(tmp)
            tree = tmp / "tree"
            (tree / rc.CARGO_TOML).parent.mkdir(parents=True)
            (tree / rc.CARGO_TOML).write_text(TOML)
            (tree / rc.CARGO_LOCK).write_text(PRISTINE)
            resolved = rc.merge_lock(PRISTINE, ENTRIES)
            # What cargo writes: checksums on every registry package.
            resolved = re.sub(r'(name = "([^"]+)"\nversion = "([^"]+)"\nsource = "[^"]+"\n)',
                              lambda m: m.group(1) + f'checksum = "{sha(m.group(2).encode()):.64}"\n', resolved)

            def fake_cargo(cmd, env, cwd):
                self.assertIn("-Zbindeps", cmd)
                self.assertEqual(env["RUSTC_BOOTSTRAP"], "1")
                (Path(cwd) / "Cargo.lock").write_text(resolved)

            work = tmp / "work"
            text = rc.resolve(tree, "157.0.8103.38", work, fake_cargo)
            self.assertEqual(text.count("[[package]]"), 4)  # thiserror 2 did not change
            self.assertIn("checksum", text)
            self.assertIn(f'cargo_toml_sha256 = "{hashlib.sha256(TOML.encode()).hexdigest()}"', text)
            # The tree was only read.
            self.assertEqual((tree / rc.CARGO_LOCK).read_text(), PRISTINE)

    def test_resolve_refuses_an_unpatched_cargo_toml(self):
        with tempfile.TemporaryDirectory() as tmp:
            tree = Path(tmp) / "tree"
            (tree / rc.CARGO_TOML).parent.mkdir(parents=True)
            (tree / rc.CARGO_TOML).write_text('[dependencies]\nserde = "1"\n')
            (tree / rc.CARGO_LOCK).write_text(PRISTINE)
            with self.assertRaisesRegex(rc.CratesError, "does not declare adblock"):
                rc.resolve(tree, "157.0.8103.38", Path(tmp) / "w", lambda *a: None)


class RepoFilesTest(unittest.TestCase):
    def test_committed_lock_loads_and_is_consistent_with_the_patch(self):
        lock = rc.load_crate_lock(REPO / rc.LOCK_FILE)
        self.assertEqual(lock.adblock, rc.ADBLOCK_VERSION)
        added = [p.name for p in lock.packages if p.checksum]
        self.assertIn("adblock", added)
        for pkg in lock.packages:
            self.assertEqual(pkg.source, rc.REGISTRY)
            self.assertRegex(pkg.checksum or "", r"^[0-9a-f]{64}$", f"{pkg.name} has no sha256")
        patch = (REPO / "patches/adblock/0003-vendor-adblock-crate.patch").read_text()
        cargo_part = patch.split("--- a/third_party/rust/chromium_crates_io/Cargo.toml", 1)[1].split("\n--- a/", 1)[0]
        added_lines = "\n".join(line[1:] for line in cargo_part.splitlines() if line.startswith("+") and not line.startswith("+++"))
        rc.check_declared("[dependencies]\n" + added_lines)

    def test_chromium_version_matches_the_helium_lock(self):
        from aerie_build import lock as helium_lock
        pins = helium_lock.load_lock(REPO / "helium.lock")
        self.assertEqual(rc.load_crate_lock(REPO / rc.LOCK_FILE).chromium_version, pins.chromium_version)

    def test_overlay_crate_patches_only_patch_crates_that_adblock_adds(self):
        lock = rc.load_crate_lock(REPO / rc.LOCK_FILE)
        added = {rc.vendor_dirname(p) for p in lock.packages if p.checksum}
        root = REPO / "overlay" / rc.PATCHES_DIR
        dirs = sorted(d.name for d in root.iterdir()) if root.is_dir() else []
        for name in dirs:
            self.assertIn(name, added, f"overlay patches {name}, which is not a crate adblock adds")
            for patch in (root / name).iterdir():
                self.assertRegex(patch.name, r"^\d{4}-.+\.patch$")
                diffs = re.findall(r"^diff --git a/(\S+) b/", patch.read_text(), re.M)
                self.assertTrue(diffs, patch)
                for path in diffs:
                    self.assertTrue(path.startswith(f"{rc.VENDOR_DIR.as_posix()}/{name}/"), path)

    def test_cargo_standalone_workspace_uses_the_same_adblock_pin(self):
        text = (REPO / "overlay/components/aerie_adblock/rust/Cargo.toml").read_text()
        self.assertIn(f'adblock = {{ version = "={rc.ADBLOCK_VERSION}"', text)
        for feature in rc.ADBLOCK_FEATURES:
            self.assertIn(f'"{feature}"', text)
        self.assertIn("default-features = false", text)


