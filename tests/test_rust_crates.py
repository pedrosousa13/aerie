def crate_bytes(name, version, files):
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for rel, data in files.items():
            info = tarfile.TarInfo(f"{name}-{version}/{rel}")
            info.size = len(data)
            tar.addfile(info, io.BytesIO(data))
    return buf.getvalue()


ADBLOCK_FILES = {"Cargo.toml": b"[package]\n", "LICENSE": b"MPL text", "src/lib.rs": b"// lib\n"}
ADBLOCK_CRATE = crate_bytes("adblock", "0.13.4", ADBLOCK_FILES)
THISERROR1_FILES = {"Cargo.toml": b"[package]\n", "src/lib.rs": b"// te1\n"}
THISERROR1_CRATE = crate_bytes("thiserror", "1.0.69", THISERROR1_FILES)


def sha(data):
    return hashlib.sha256(data).hexdigest()


ENTRIES = [
    rc.Package("adblock", "0.13.4", REG, sha(ADBLOCK_CRATE), ("bitflags", "thiserror 1.0.69")),
    rc.Package("bitflags", "2.13.2", REG, "b" * 64, ("serde_core",)),  # changed: a new dependency
    rc.Package("thiserror", "1.0.69", REG, sha(THISERROR1_CRATE), ()),
    rc.Package("thiserror", "2.0.21", REG, "c" * 64, ()),  # changed? no: only the name needs the version now
    rc.Package("user", "0.1.0", REG, "d" * 64, ("thiserror 2.0.21",)),  # changed: disambiguated dependency
]


def make_lock(entries=ENTRIES, toml=TOML, pristine=PRISTINE, chromium="157.0.8103.38", adblock="0.13.4"):
    text = rc.render_crate_lock(chromium, toml, pristine, entries)
    return text.replace(f'adblock = "{rc.ADBLOCK_VERSION}"', f'adblock = "{adblock}"', 1)


class Tree:
    """A fake source tree with Cargo.toml, Cargo.lock, and a vendor directory."""

    def __init__(self, test, toml=TOML, lock=PRISTINE):
        self._tmp = tempfile.TemporaryDirectory()
        test.addCleanup(self._tmp.cleanup)
        self.root = Path(self._tmp.name)
        (self.root / rc.CARGO_TOML).parent.mkdir(parents=True)
        (self.root / rc.CARGO_TOML).write_text(toml)
        (self.root / rc.GNRT_CONFIG).write_text(GNRT)
        (self.root / rc.CARGO_LOCK).write_text(lock)

    def vendor(self, pkg, files):
        directory = self.root / rc.VENDOR_DIR / rc.vendor_dirname(pkg)
        for rel, data in files.items():
            (directory / rel).parent.mkdir(parents=True, exist_ok=True)
            (directory / rel).write_bytes(data)
        return directory


class ParseAndMergeTest(unittest.TestCase):
    def test_merge_with_nothing_is_the_original(self):
        self.assertEqual(rc.merge_lock(PRISTINE, []), PRISTINE)

    def test_merge_adds_replaces_and_keeps_cargo_order(self):
        merged = rc.merge_lock(PRISTINE, ENTRIES)
        pkgs = rc.parse_lock(merged)
        self.assertEqual(list(pkgs), [("adblock", "0.13.4"), ("bitflags", "2.13.2"), ("chromium", "0.1.0"),
                                      ("serde", "1.0.1"), ("thiserror", "1.0.69"), ("thiserror", "2.0.21"),
                                      ("user", "0.1.0")])
        self.assertEqual(pkgs[("bitflags", "2.13.2")].dependencies, ("serde_core",))
        self.assertEqual(pkgs[("user", "0.1.0")].dependencies, ("thiserror 2.0.21",))
        self.assertNotIn("checksum", merged)

    def test_merge_does_not_touch_other_entries(self):
        pkgs = rc.parse_lock(rc.merge_lock(PRISTINE, ENTRIES))
        self.assertEqual(pkgs[("chromium", "0.1.0")].dependencies, ("bitflags", "serde"))

    def test_version_order_is_numeric(self):
        a = rc.Package("x", "1.10.0", REG, None, ())
        b = rc.Package("x", "1.9.0", REG, None, ())
        merged = rc.merge_lock(PRISTINE, [a, b])
        self.assertLess(merged.index('version = "1.9.0"'), merged.index('version = "1.10.0"'))

    def test_checksum_lines_are_ignored_by_the_digest(self):
        with_sum = PRISTINE.replace(f'source = "{REG}"\n', f'source = "{REG}"\nchecksum = "{"a" * 64}"\n', 1)
        self.assertEqual(rc.lock_digest(with_sum), rc.lock_digest(PRISTINE))

    def test_duplicate_package_is_an_error(self):
        with self.assertRaises(rc.CratesError):
            rc.parse_lock(PRISTINE + '\n[[package]]\nname = "serde"\nversion = "1.0.1"\n')


class CrateLockTest(unittest.TestCase):
    def load(self, text):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "crates.lock.toml"
            path.write_text(text)
            return rc.load_crate_lock(path)

    def test_round_trip(self):
        lock = self.load(make_lock())
        self.assertEqual(lock.adblock, "0.13.4")
        self.assertEqual([p.name for p in lock.packages], ["adblock", "bitflags", "thiserror", "thiserror", "user"])
        pristine = rc.parse_lock(PRISTINE)
        self.assertEqual([(p.name, p.version) for p in lock.added(pristine)],
                         [("adblock", "0.13.4"), ("thiserror", "1.0.69")])
        self.assertEqual([p.name for p in lock.changed(pristine)], ["bitflags", "thiserror", "user"])

    def test_non_registry_package_is_refused(self):
        text = make_lock().replace(REG, "git+https://example.com/x", 1)
        with self.assertRaisesRegex(rc.CratesError, "not from crates.io"):
            self.load(text)

    def test_version_must_match_the_tool(self):
        with self.assertRaisesRegex(rc.CratesError, "wants"):
            self.load(make_lock(adblock="0.13.5"))

    def test_missing_hash_fields_are_refused(self):
        text = re.sub(r"cargo_lock_sha256 = .*\n", "", make_lock())
        with self.assertRaisesRegex(rc.CratesError, "missing cargo_lock_sha256"):
            self.load(text)


