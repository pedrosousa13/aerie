class VerifyResolutionTest(unittest.TestCase):
    def lock(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "l.toml"
            path.write_text(make_lock())
            return rc.load_crate_lock(path)

    def test_exact_result_passes(self):
        tree = Tree(self, lock=rc.merge_lock(PRISTINE, ENTRIES))
        rc.verify_resolution(tree.root, self.lock(), PRISTINE)

    def test_extra_package_from_gnrt_is_caught(self):
        extra = rc.Package("evil", "1.0.0", REG, None, ())
        tree = Tree(self, lock=rc.merge_lock(PRISTINE, ENTRIES + [extra]))
        with self.assertRaisesRegex(rc.CratesError, "unexpected package evil"):
            rc.verify_resolution(tree.root, self.lock(), PRISTINE)

    def test_gnrt_picking_another_version_is_caught(self):
        moved = [p if p.name != "thiserror" or p.version != "1.0.69" else rc.Package("thiserror", "1.0.70", REG, None, ())
                 for p in ENTRIES]
        tree = Tree(self, lock=rc.merge_lock(PRISTINE, moved))
        with self.assertRaises(rc.CratesError) as ctx:
            rc.verify_resolution(tree.root, self.lock(), PRISTINE)
        self.assertIn("thiserror 1.0.70", str(ctx.exception))
        self.assertIn("missing package thiserror 1.0.69", str(ctx.exception))

    def test_changed_dependencies_are_caught(self):
        tampered = [p if p.name != "bitflags" else rc.Package("bitflags", "2.13.2", REG, None, ("serde_core", "other"))
                    for p in ENTRIES]
        tree = Tree(self, lock=rc.merge_lock(PRISTINE, tampered))
        with self.assertRaisesRegex(rc.CratesError, "bitflags 2.13.2 differs"):
            rc.verify_resolution(tree.root, self.lock(), PRISTINE)

    def test_a_dropped_chromium_package_is_caught(self):
        text = rc.merge_lock(PRISTINE, ENTRIES)
        text = re.sub(r'\[\[package\]\]\nname = "serde"\nversion = "1.0.1"\nsource = "[^"]+"\n\n', "", text)
        tree = Tree(self, lock=text)
        with self.assertRaisesRegex(rc.CratesError, "missing package serde"):
            rc.verify_resolution(tree.root, self.lock(), PRISTINE)

    def test_non_registry_source_is_caught(self):
        text = rc.merge_lock(PRISTINE, ENTRIES).replace(f'name = "serde"\nversion = "1.0.1"\nsource = "{REG}"',
                                                       'name = "serde"\nversion = "1.0.1"\nsource = "git+https://x/y"')
        tree = Tree(self, lock=text)
        with self.assertRaises(rc.CratesError):
            rc.verify_resolution(tree.root, self.lock(), PRISTINE)


class FetchCrateTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.cache = Path(self._tmp.name)

    def opener(self, served):
        calls = []

        def fn(request):
            calls.append(request.full_url)
            return io.BytesIO(served)

        fn.calls = calls
        return fn

    def test_hash_is_checked_and_download_cached(self):
        pkg = ENTRIES[0]
        opener = self.opener(ADBLOCK_CRATE)
        self.assertEqual(rc.fetch_crate(pkg, self.cache, opener, lambda m: None), ADBLOCK_CRATE)
        self.assertEqual(opener.calls, ["https://static.crates.io/crates/adblock/adblock-0.13.4.crate"])
        rc.fetch_crate(pkg, self.cache, opener, lambda m: None)
        self.assertEqual(len(opener.calls), 1)

    def test_wrong_bytes_are_refused_and_not_cached(self):
        with self.assertRaisesRegex(rc.CratesError, "crates.io served sha256"):
            rc.fetch_crate(ENTRIES[0], self.cache, self.opener(ADBLOCK_CRATE + b"x"), lambda m: None)
        self.assertEqual(list(self.cache.iterdir()), [])

    def test_missing_lock_hash_is_refused(self):
        with self.assertRaisesRegex(rc.CratesError, "no sha256"):
            rc.fetch_crate(rc.Package("x", "1.0.0", REG, None, ()), self.cache, self.opener(b""), lambda m: None)

    def test_crate_with_path_traversal_is_refused(self):
        evil = crate_bytes("adblock", "0.13.4", {"../evil": b"x", "Cargo.toml": b"x"})
        with self.assertRaisesRegex(rc.CratesError, "unexpected path"):
            rc.crate_files(evil, ENTRIES[0])

    def test_not_a_crate_is_refused(self):
        with self.assertRaisesRegex(rc.CratesError, "not a valid"):
            rc.crate_files(b"not gzip", ENTRIES[0])


class VerifyVendoredTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.cache = Path(self._tmp.name)
        self.tree = Tree(self)
        self.adblock, self.thiserror = ENTRIES[0], ENTRIES[2]
        self.served = {"adblock": ADBLOCK_CRATE, "thiserror": THISERROR1_CRATE}

    def verify(self):
        def opener(request):
            return io.BytesIO(self.served[request.full_url.split("/")[4]])
        return rc.verify_vendored(self.tree.root, [self.adblock, self.thiserror], self.cache, opener, lambda m: None)

    def vendor_all(self):
        self.tree.vendor(self.adblock, ADBLOCK_FILES)
        self.tree.vendor(self.thiserror, THISERROR1_FILES)

    def test_identical_vendor_passes(self):
        self.vendor_all()
        self.assertEqual(self.verify(), 2)

    def test_modified_file_is_caught(self):
        self.vendor_all()
        (self.tree.root / rc.VENDOR_DIR / "adblock-v0_13" / "src/lib.rs").write_bytes(b"// backdoor\n")
        with self.assertRaisesRegex(rc.CratesError, r"src/lib.rs differs"):
            self.verify()

    def test_missing_file_is_caught(self):
        self.vendor_all()
        (self.tree.root / rc.VENDOR_DIR / "adblock-v0_13" / "LICENSE").unlink()
        with self.assertRaisesRegex(rc.CratesError, "LICENSE is missing"):
            self.verify()

    def test_extra_source_file_is_caught_but_extra_docs_are_not(self):
        self.vendor_all()
        directory = self.tree.root / rc.VENDOR_DIR / "adblock-v0_13"
        (directory / "NOTES.md").write_text("fine")
        self.assertEqual(self.verify(), 2)
        (directory / "src" / "extra.rs").write_text("fn evil() {}")
        with self.assertRaisesRegex(rc.CratesError, "extra.rs is source code"):
            self.verify()

    def test_unvendored_crate_is_caught(self):
        self.tree.vendor(self.adblock, ADBLOCK_FILES)
        with self.assertRaisesRegex(rc.CratesError, "not vendored"):
            self.verify()

    def test_crates_io_serving_other_bytes_than_the_lock_is_caught(self):
        self.vendor_all()
        self.served["adblock"] = crate_bytes("adblock", "0.13.4", {"Cargo.toml": b"x"})
        with self.assertRaisesRegex(rc.CratesError, "crates.io served sha256"):
            self.verify()


class CreditsTest(unittest.TestCase):
    def lock(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "l.toml"
            path.write_text(make_lock())
            return rc.load_crate_lock(path)

    def tree_with(self, readme, license_exists=True):
        tree = Tree(self)
        gn = tree.root / "third_party/rust/adblock/v0_13"
        gn.mkdir(parents=True)
        (gn / "BUILD.gn").write_text("# gn")
