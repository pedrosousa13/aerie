"""Vendoring adblock-rust with `gnrt`, under a committed lock and a hash check.

Chromium keeps third-party Rust crates in `//third_party/rust`, generated by
`gnrt` from `chromium_crates_io/Cargo.toml` and `Cargo.lock`. Aerie adds one
dependency there, `adblock` (patches/adblock/0003-vendor-adblock-crate.patch).
`gnrt vendor` would pick the newest crates.io versions of everything adblock
needs, so Aerie pins the whole result first and checks it afterwards:

1. `rust/crates.lock.toml` (committed) lists every package that adblock adds to
   Chromium's `Cargo.lock`, or whose entry in it changes, with the crates.io
   sha256 of each added crate. It was resolved against one exact
   `Cargo.toml` and `Cargo.lock`, whose hashes it records. If Chromium's
   files differ (a Chromium bump), the lock is stale and the build stops:
   run `./aerie crates resolve`, review the diff, commit it.
2. The build writes those entries into the tree's `Cargo.lock`, so
   `gnrt vendor` resolves to exactly the locked versions.
3. After `gnrt vendor` and `gnrt gen` the build checks, and stops on any
   difference: the final `Cargo.lock` is the pristine one plus the locked
   entries and nothing else; every added crate's `.crate` file, downloaded
   from crates.io, has the locked sha256; every file in it is present,
   byte for byte, in `third_party/rust/chromium_crates_io/vendor`; and the
   generated README.chromium says MPL-2.0 and shipped (that is what puts
   adblock-rust on chrome://credits).

Chromium strips the `checksum` lines from its lock, and empties the
checksum files `cargo vendor` writes, so the hash check cannot lean on
cargo. The comparison against the `.crate` file is the check.

Everything here is plain functions over text and files, so the tests need no
network and no Chromium tree. Only `resolve` and `run_gnrt` run programs.
"""

from __future__ import annotations

import hashlib
import io
import re
import subprocess
import tarfile
import tomllib
import urllib.error
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Iterable, Sequence

from . import fallback

ADBLOCK_NAME = "adblock"
ADBLOCK_VERSION = "0.13.4"
ADBLOCK_FEATURES = ("full-regex-handling", "single-thread")
ADBLOCK_LICENSE = "MPL-2.0"
LOCK_FILE = Path("rust") / "crates.lock.toml"
SCHEMA = 1
REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"
CRATE_URL = "https://static.crates.io/crates/{name}/{name}-{version}.crate"
MAX_CRATE_BYTES = 64 * 1024 * 1024

CARGO_TOML = Path("third_party") / "rust" / "chromium_crates_io" / "Cargo.toml"
CARGO_LOCK = Path("third_party") / "rust" / "chromium_crates_io" / "Cargo.lock"
GNRT_CONFIG = Path("third_party") / "rust" / "chromium_crates_io" / "gnrt_config.toml"
VENDOR_DIR = Path("third_party") / "rust" / "chromium_crates_io" / "vendor"
ROOT_PACKAGE = "chromium"
PRISTINE_BACKUP = ".aerie-cargo-lock.pristine"

# Extra files in a vendored crate are harmless, except source code that
# the tarball does not have.
_CODE_SUFFIXES = (".rs", ".c", ".cc", ".cpp", ".h", ".hpp", ".s", ".S", ".asm", ".py", ".sh")


class CratesError(RuntimeError):
    """The crate lock, the vendored crates or the credits metadata failed a check."""


# --- Cargo.lock text -------------------------------------------------------


@dataclass(frozen=True)
class Package:
    name: str
    version: str
    source: str | None
    checksum: str | None
    dependencies: tuple[str, ...]

    @property
    def key(self) -> tuple[str, str]:
        return (self.name, self.version)

    def same_entry(self, other: "Package") -> bool:
        """Equal apart from the checksum, which Chromium's lock leaves out."""
        return (self.name, self.version, self.source, self.dependencies) == (
            other.name, other.version, other.source, other.dependencies)


def parse_lock(text: str) -> dict[tuple[str, str], Package]:
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        raise CratesError(f"Cargo.lock does not parse: {exc}") from exc
    packages: dict[tuple[str, str], Package] = {}
    for entry in data.get("package", []):
        pkg = Package(entry["name"], entry["version"], entry.get("source"), entry.get("checksum"),
                      tuple(entry.get("dependencies", ())))
        if pkg.key in packages:
            raise CratesError(f"Cargo.lock lists {pkg.name} {pkg.version} twice")
        packages[pkg.key] = pkg
    return packages


def _version_key(version: str) -> tuple:
    core = re.split(r"[-+]", version, maxsplit=1)[0]
    nums = tuple(int(p) if p.isdigit() else 0 for p in core.split("."))
    # A pre-release sorts before its release.
    return nums + (0 if "-" in version else 1,)


def render_package(pkg: Package, with_checksum: bool) -> str:
    lines = ["[[package]]", f'name = "{pkg.name}"', f'version = "{pkg.version}"']
    if pkg.source:
        lines.append(f'source = "{pkg.source}"')
    if with_checksum and pkg.checksum:
        lines.append(f'checksum = "{pkg.checksum}"')
    if pkg.dependencies:
        lines.append("dependencies = [")
        lines += [f' "{dep}",' for dep in pkg.dependencies]
        lines.append("]")
    return "\n".join(lines) + "\n"


def strip_checksums(text: str) -> str:
    return "".join(line for line in text.splitlines(keepends=True) if not line.startswith("checksum = "))


def lock_digest(text: str) -> str:
    """sha256 of a Cargo.lock without its checksum lines, as Chromium keeps it."""
    return hashlib.sha256(strip_checksums(text).encode()).hexdigest()


def merge_lock(pristine_text: str, entries: Iterable[Package]) -> str:
    """Put entries into a Cargo.lock: replace a package with the same name and version, else add.

    The output has no checksum lines (Chromium's convention) and keeps cargo's
    order: by name, then version.
    """
    base = strip_checksums(pristine_text)
    header, _, rest = base.partition("[[package]]")
    blocks = ["[[package]]" + b for b in re.split(r"(?m)^\[\[package\]\]", "[[package]]" + rest)[1:]] if rest else []
    parsed = []
    for block in blocks:
        pkg = next(iter(parse_lock(block).values()))
        parsed.append((pkg, block.rstrip("\n") + "\n"))
    by_key = {pkg.key: text for pkg, text in parsed}
    pkgs = {pkg.key: pkg for pkg, _ in parsed}
    for entry in entries:
        by_key[entry.key] = render_package(entry, with_checksum=False)
        pkgs[entry.key] = entry
    ordered = sorted(by_key, key=lambda k: (k[0], _version_key(k[1])))
    return header + "\n".join(by_key[k] for k in ordered)


# --- The committed lock ----------------------------------------------------


@dataclass(frozen=True)
class CrateLock:
    chromium_version: str
    adblock: str
    cargo_toml_sha256: str
    cargo_lock_sha256: str
    packages: tuple[Package, ...]

    def added(self, pristine: dict[tuple[str, str], Package]) -> list[Package]:
        return [p for p in self.packages if p.key not in pristine]

    def changed(self, pristine: dict[tuple[str, str], Package]) -> list[Package]:
        return [p for p in self.packages if p.key in pristine]


def load_crate_lock(path: Path) -> CrateLock:
    try:
        data = tomllib.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise CratesError(f"cannot read the crate lock {path}: {exc}") from exc
    if data.get("schema") != SCHEMA:
        raise CratesError(f"{path}: unsupported schema {data.get('schema')!r}")
    packages = []
    for entry in data.get("package", []):
        pkg = Package(entry["name"], entry["version"], entry.get("source"), entry.get("checksum"),
                      tuple(entry.get("dependencies", ())))
        if pkg.source != REGISTRY:
            raise CratesError(f"{path}: {pkg.name} {pkg.version} is not from crates.io ({pkg.source!r})")
        packages.append(pkg)
    for field in ("chromium_version", "adblock", "cargo_toml_sha256", "cargo_lock_sha256"):
        if not data.get(field):
            raise CratesError(f"{path}: missing {field}")
    lock = CrateLock(data["chromium_version"], data["adblock"], data["cargo_toml_sha256"],
                     data["cargo_lock_sha256"], tuple(packages))
    if lock.adblock != ADBLOCK_VERSION:
        raise CratesError(f"{path}: pins adblock {lock.adblock}, tools/aerie_build/rust_crates.py wants {ADBLOCK_VERSION}")
    if not any(p.name == ADBLOCK_NAME and p.version == lock.adblock for p in lock.packages):
        raise CratesError(f"{path}: {ADBLOCK_NAME} {lock.adblock} is not among the packages")
    return lock


def render_crate_lock(chromium_version: str, cargo_toml: str, cargo_lock: str,
                      packages: Sequence[Package]) -> str:
    head = [
        "# Written by `./aerie crates resolve`. Review the diff, then commit it.",
        "#",
        "# Every package that adblock adds to Chromium's third_party/rust/chromium_crates_io/",
        "# Cargo.lock, or whose entry there changes. Added crates carry the sha256 of their",
        "# .crate file on crates.io. See tools/aerie_build/rust_crates.py.",
        f"schema = {SCHEMA}",
        f'chromium_version = "{chromium_version}"',
        f'adblock = "{ADBLOCK_VERSION}"',
        "# Hashes of the files this was resolved against: Cargo.toml as the Aerie patch leaves it,",
        "# Cargo.lock as Chromium ships it (without checksum lines).",
        f'cargo_toml_sha256 = "{hashlib.sha256(cargo_toml.encode()).hexdigest()}"',
        f'cargo_lock_sha256 = "{lock_digest(cargo_lock)}"',
        "",
    ]
    ordered = sorted(packages, key=lambda p: (p.name, _version_key(p.version)))
    return "\n".join(head) + "\n" + "\n".join(render_package(p, with_checksum=True) for p in ordered)


# --- Resolving (maintainer command) ----------------------------------------


def resolve(tree: Path, chromium_version: str, work: Path,
            runner: Callable[[Sequence[str], dict, Path], None] | None = None) -> str:
    """Resolve adblock against the tree's Cargo.toml / Cargo.lock; return the new lock text.

    Copies the two files into `work` and runs the tree's own cargo there, so
    nothing in `tree` is written. Needs network access to crates.io.
    """
    cargo = Path(tree) / "third_party" / "rust-toolchain" / "bin" / "cargo"
    toml_text = (Path(tree) / CARGO_TOML).read_text(encoding="utf-8")
    pristine_text = (Path(tree) / CARGO_LOCK).read_text(encoding="utf-8")
    check_declared(toml_text)
    work = Path(work)
    (work / "src").mkdir(parents=True, exist_ok=True)
    (work / "src" / "lib.rs").write_text("")
    (work / "Cargo.toml").write_text(toml_text, encoding="utf-8")
    (work / "Cargo.lock").write_text(strip_checksums(pristine_text), encoding="utf-8")
    env = {"PATH": "/usr/bin:/bin", "HOME": str(work / "home"), "CARGO_HOME": str(work / "cargo-home"),
           "RUSTC_BOOTSTRAP": "1"}
    cmd = [str(cargo), "metadata", "--format-version", "1", "-Zbindeps", "--manifest-path", str(work / "Cargo.toml")]
    run = runner or _run
    run(cmd, env, work)
    resolved = parse_lock((work / "Cargo.lock").read_text(encoding="utf-8"))
    pristine = parse_lock(pristine_text)
    entries = []
    for key, pkg in resolved.items():
        if pkg.name == ROOT_PACKAGE:
            continue
        old = pristine.get(key)
        if old is None or not old.same_entry(pkg):
            entries.append(pkg)
    for pkg in entries:
        if pkg.key not in pristine and (not pkg.checksum or pkg.source != REGISTRY):
            raise CratesError(f"{pkg.name} {pkg.version} has no crates.io checksum in the resolved lock")
    removed = [k for k in pristine if k not in resolved and k[0] != ROOT_PACKAGE]
    if removed:
        raise CratesError(f"resolving dropped Chromium packages: {removed[:5]}")
    return render_crate_lock(chromium_version, toml_text, pristine_text, entries)


def _run(cmd: Sequence[str], env: dict, cwd: Path) -> None:
    proc = subprocess.run(cmd, env=env, cwd=cwd, stdin=subprocess.DEVNULL, capture_output=True, text=True)
    if proc.returncode != 0:
        raise CratesError(f"{' '.join(cmd)} failed:\n{proc.stderr[-2000:]}")


# --- Checks before and after gnrt ------------------------------------------


def check_declared(cargo_toml: str) -> None:
    """The Aerie patch must have declared exactly adblock, with the expected features."""
    try:
        deps = tomllib.loads(cargo_toml)["dependencies"]
    except (tomllib.TOMLDecodeError, KeyError) as exc:
        raise CratesError(f"chromium_crates_io/Cargo.toml has no usable [dependencies]: {exc}") from exc
    spec = deps.get(ADBLOCK_NAME)
    if not isinstance(spec, dict):
        raise CratesError("chromium_crates_io/Cargo.toml does not declare adblock "
                          "(patches/adblock/0003-vendor-adblock-crate.patch not applied?)")
    if spec.get("version") != f"={ADBLOCK_VERSION}":
        raise CratesError(f"adblock must be pinned with version = \"={ADBLOCK_VERSION}\", got {spec.get('version')!r}")
    if spec.get("default-features") is not False or tuple(spec.get("features", ())) != ADBLOCK_FEATURES:
        raise CratesError(f"adblock must use default-features = false and features = {list(ADBLOCK_FEATURES)}")


def check_gnrt_config(text: str) -> None:
    """The Aerie patch must have set what gnrt and GN need for adblock (found in review of the first slice).

    * adblock and regex in group 'safe': in 'test' they make adblock testonly and "Shipped: no",
      which also leaves it off chrome://credits;
    * flatbuffers without build.rs: it turns on nightly features under Chromium's rustc, which
      Chromium forbids;
    * thiserror v1 and v2 configured apart: only v2's build script writes private.rs.
    """
    try:
        crates = tomllib.loads(text)["crate"]
    except (tomllib.TOMLDecodeError, KeyError) as exc:
        raise CratesError(f"gnrt_config.toml has no usable [crate] tables: {exc}") from exc
    for name in ("adblock", "regex"):
        if crates.get(name, {}).get("group") != "safe":
            raise CratesError(f"gnrt_config.toml: [crate.{name}] must have group = 'safe' "
                              "(patches/adblock/0003 not applied?)")
    if crates.get("flatbuffers", {}).get("remove_build_rs") is not True:
        raise CratesError("gnrt_config.toml: [crate.flatbuffers] must have remove_build_rs = true")
    if "thiserror" in crates:
        raise CratesError("gnrt_config.toml: [crate.thiserror] must be split into thiserror@v1 and thiserror@v2")
    v1, v2 = crates.get("thiserror@v1"), crates.get("thiserror@v2")
    if v1 is None or v2 is None:
        raise CratesError("gnrt_config.toml: thiserror@v1 and thiserror@v2 sections are both needed")
    if v1.get("build_script_outputs"):
        raise CratesError("gnrt_config.toml: thiserror@v1 must not declare build_script_outputs")
    if v2.get("build_script_outputs") != ["private.rs"]:
        raise CratesError("gnrt_config.toml: thiserror@v2 must declare build_script_outputs = [\"private.rs\"]")


def check_base(lock: CrateLock, chromium_version: str, cargo_toml: str, cargo_lock: str) -> None:
    """Stop if the crate lock was resolved against other files than the tree has."""
    stale = "rust/crates.lock.toml is stale: run ./aerie crates resolve, review the diff and commit it. "
    if lock.chromium_version != chromium_version:
        raise CratesError(stale + f"It is for Chromium {lock.chromium_version}, the tree is {chromium_version}.")
    if hashlib.sha256(cargo_toml.encode()).hexdigest() != lock.cargo_toml_sha256:
        raise CratesError(stale + "chromium_crates_io/Cargo.toml differs from the one it was resolved against.")
    if lock_digest(cargo_lock) != lock.cargo_lock_sha256:
        raise CratesError(stale + "chromium_crates_io/Cargo.lock differs from the one it was resolved against.")


def verify_resolution(tree: Path, lock: CrateLock, pristine_text: str) -> None:
    """After gnrt vendor: the tree's Cargo.lock is the pristine one plus the locked entries, and nothing else."""
    pristine = parse_lock(pristine_text)
    expected = dict(pristine)
    for pkg in lock.packages:
        expected[pkg.key] = pkg
    actual = parse_lock((Path(tree) / CARGO_LOCK).read_text(encoding="utf-8"))
    problems = []
    for key in sorted(set(expected) | set(actual)):
        if key[0] == ROOT_PACKAGE:
            continue
        want, got = expected.get(key), actual.get(key)
        if want is None:
            problems.append(f"unexpected package {key[0]} {key[1]}")
        elif got is None:
            problems.append(f"missing package {key[0]} {key[1]}")
        elif not want.same_entry(got):
            problems.append(f"entry for {key[0]} {key[1]} differs from the lock")
        elif got.source != REGISTRY:
            problems.append(f"{key[0]} {key[1]} is not from crates.io")
    if problems:
        raise CratesError("the vendored crate set is not the locked one:\n  " + "\n  ".join(problems[:20]))


def epoch(version: str) -> str:
    """gnrt's directory suffix for a version: v1, v0_13, v0_0_4."""
    major, minor, patch = (int(p) for p in re.split(r"[-+]", version, maxsplit=1)[0].split(".")[:3])
    if major:
        return f"v{major}"
    return f"v0_{minor}" if minor else f"v0_0_{patch}"


def vendor_dirname(pkg: Package) -> str:
    return f"{pkg.name}-{epoch(pkg.version)}"


def fetch_crate(pkg: Package, cache: Path, opener: fallback.Opener = fallback.default_opener,
                log: Callable[[str], None] = print) -> bytes:
    """The .crate file of pkg, checked against the locked sha256. Cached by hash."""
    if not pkg.checksum or not re.fullmatch(r"[0-9a-f]{64}", pkg.checksum):
        raise CratesError(f"{pkg.name} {pkg.version}: the lock has no sha256")
    cached = Path(cache) / f"{pkg.checksum}-{pkg.name}-{pkg.version}.crate"
    if cached.is_file():
        data = cached.read_bytes()
        if hashlib.sha256(data).hexdigest() == pkg.checksum:
            return data
        cached.unlink()
    url = CRATE_URL.format(name=pkg.name, version=pkg.version)
    log(f"crate {pkg.name} {pkg.version}: downloading {url}")
    try:
        response = opener(fallback._request(url))
        data = response.read(MAX_CRATE_BYTES + 1)
    except (urllib.error.URLError, OSError, TimeoutError) as exc:
        raise CratesError(f"cannot download {url}: {exc}") from exc
    if len(data) > MAX_CRATE_BYTES:
        raise CratesError(f"{url} is larger than {MAX_CRATE_BYTES} bytes")
    actual = hashlib.sha256(data).hexdigest()
    if actual != pkg.checksum:
        raise CratesError(f"{pkg.name} {pkg.version}: crates.io served sha256 {actual}, the lock says {pkg.checksum}")
    Path(cache).mkdir(parents=True, exist_ok=True)
    cached.write_bytes(data)
    return data


def crate_files(data: bytes, pkg: Package) -> dict[str, bytes]:
    """Regular files of a .crate (a gzip tar), keyed by path inside the package directory."""
    prefix = f"{pkg.name}-{pkg.version}/"
    files: dict[str, bytes] = {}
    try:
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
            for member in tar:
                if not member.isreg():
                    continue
                if not member.name.startswith(prefix) or ".." in Path(member.name).parts:
                    raise CratesError(f"{pkg.name} {pkg.version}: unexpected path {member.name!r} in the crate")
                handle = tar.extractfile(member)
                assert handle is not None
                files[member.name[len(prefix):]] = handle.read()
    except tarfile.TarError as exc:
        raise CratesError(f"{pkg.name} {pkg.version}: not a valid .crate file: {exc}") from exc
    if "Cargo.toml" not in files:
        raise CratesError(f"{pkg.name} {pkg.version}: the crate has no Cargo.toml")
    return files


def verify_vendored(tree: Path, packages: Iterable[Package], cache: Path,
                    opener: fallback.Opener = fallback.default_opener,
                    log: Callable[[str], None] = print) -> int:
    """Check each added crate in the vendor directory against its locked .crate file. Returns the count."""
    count = 0
    for pkg in packages:
        files = crate_files(fetch_crate(pkg, cache, opener, log), pkg)
        directory = Path(tree) / VENDOR_DIR / vendor_dirname(pkg)
        if not directory.is_dir():
            raise CratesError(f"{pkg.name} {pkg.version} is not vendored: {directory} is missing")
        problems = []
        for rel, data in sorted(files.items()):
            target = directory / rel
            if not target.is_file():
                problems.append(f"{rel} is missing")
            elif target.read_bytes() != data:
                problems.append(f"{rel} differs from the crate")
        known = set(files)
        for path in directory.rglob("*"):
            rel = path.relative_to(directory).as_posix()
            if path.is_file() and rel not in known and rel.endswith(_CODE_SUFFIXES):
                problems.append(f"{rel} is source code that is not in the crate")
        if problems:
            raise CratesError(
                f"{pkg.name} {pkg.version}: vendored files do not match crates.io:\n  " + "\n  ".join(problems[:20]))
        count += 1
    return count


def verify_credits(tree: Path, lock: CrateLock) -> None:
    """adblock-rust must be generated as shipped, MPL-2.0, with a licence file that exists."""
    adblock = next(p for p in lock.packages if p.name == ADBLOCK_NAME)
    gn_dir = Path(tree) / "third_party" / "rust" / ADBLOCK_NAME / epoch(adblock.version)
    readme = gn_dir / "README.chromium"
    if not (gn_dir / "BUILD.gn").is_file():
        raise CratesError(f"gnrt gen did not write {gn_dir / 'BUILD.gn'}")
    if not readme.is_file():
        raise CratesError(f"gnrt gen did not write {readme}")
    fields = {}
    for line in readme.read_text(encoding="utf-8").splitlines():
        key, sep, value = line.partition(":")
        if sep:
            fields.setdefault(key.strip(), value.strip())
    if fields.get("License") != ADBLOCK_LICENSE:
        raise CratesError(f"{readme}: License is {fields.get('License')!r}, expected {ADBLOCK_LICENSE!r}")
    if fields.get("Shipped", "").lower() != "yes":
        raise CratesError(f"{readme}: Shipped is {fields.get('Shipped')!r}, so adblock-rust would be left out of chrome://credits")
    license_file = fields.get("License File", "")
    resolved = Path(tree) / license_file[2:] if license_file.startswith("//") else gn_dir / license_file
    if not license_file or not resolved.is_file():
        raise CratesError(f"{readme}: License File {license_file!r} does not exist")


# --- Running gnrt ----------------------------------------------------------


def run_gnrt(tree: Path, python: Path | str, env: dict, log, runner) -> None:
    """`gnrt vendor` then `gnrt gen`, through Chromium's own wrapper (builds gnrt with the in-tree cargo)."""
    script = Path(tree) / "tools" / "crates" / "run_gnrt.py"
    if not script.is_file():
        raise CratesError(f"{script} is missing; this Chromium tree has no gnrt")
    for sub in ("vendor", "gen"):
        runner(log, [python, script, sub], env, cwd=Path(tree))


def vendor_adblock(tree: Path, repo: Path, chromium_version: str, cache: Path, python: Path | str, env: dict,
                   log, runner, opener: fallback.Opener = fallback.default_opener) -> None:
    """The whole vendor step. Raises CratesError, and leaves the tree as the failed check found it.

    Safe to run again after an interruption: the pristine Cargo.lock is kept in
    the tree on the first run, and every run pins from that copy.
    """
    tree = Path(tree)
    lock = load_crate_lock(Path(repo) / LOCK_FILE)
    backup = tree / PRISTINE_BACKUP
    if backup.is_file():
        pristine_text = backup.read_text(encoding="utf-8")
    else:
        pristine_text = (tree / CARGO_LOCK).read_text(encoding="utf-8")
        backup.write_text(pristine_text, encoding="utf-8")
    toml_text = (tree / CARGO_TOML).read_text(encoding="utf-8")
    check_declared(toml_text)
    check_gnrt_config((tree / GNRT_CONFIG).read_text(encoding="utf-8"))
    check_base(lock, chromium_version, toml_text, pristine_text)
    (tree / CARGO_LOCK).write_text(merge_lock(pristine_text, lock.packages), encoding="utf-8")
    log(f"crates: pinned {len(lock.packages)} package(s) from {LOCK_FILE}")
    run_gnrt(tree, python, env, log, runner)
    verify_resolution(tree, lock, pristine_text)
